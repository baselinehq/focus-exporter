package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"text/template"
)

type column struct {
	Name     string `json:"name"`
	Datatype string `json:"datatype"`
	Pointer  bool   `json:"pointer"`
}

type field struct {
	Name string
	Type string
	Tag  string
}

const columnsPath = "columns.json"
const outputPath = "record_gen.go"

var goType = map[string]string{
	"decimal":  "string",
	"string":   "string",
	"datetime": "time.Time",
	"json":     "json.RawMessage",
}

const recordTemplate = `// Code generated by internal/gen. DO NOT EDIT.

package focus

import (
	"encoding/json"
	"time"
)

type Record struct {
{{- range .Fields }}
	{{ .Name }} {{ .Type }} ` + "`json:\"{{ .Tag }}\"`" + `
{{- end }}

	Extensions map[string]any ` + "`json:\"-\"`" + `
}
`

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	raw, err := os.ReadFile(columnsPath)
	if err != nil {
		return err
	}
	var cols []column
	if err := json.Unmarshal(raw, &cols); err != nil {
		return err
	}

	fields := make([]field, 0, len(cols))
	for _, c := range cols {
		base, ok := goType[c.Datatype]
		if !ok {
			return fmt.Errorf("unknown datatype %q for column %q", c.Datatype, c.Name)
		}
		f := field{Name: c.Name, Type: base, Tag: c.Name}
		if c.Pointer {
			f.Type = "*" + base
			f.Tag = c.Name + ",omitempty"
		}
		fields = append(fields, f)
	}

	tmpl, err := template.New("record").Parse(recordTemplate)
	if err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, struct{ Fields []field }{fields}); err != nil {
		return err
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(outputPath, formatted, 0o644)
}
